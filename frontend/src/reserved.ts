const sets: Partial<Record<DdlDialect, Set<string>>> = {};

/** True when `name` (as a whole) is a reserved word of the database. */
export function isReserved(name: string, db: DdlDialect): boolean {
  let set = sets[db];
  if (!set) {
    const src = db === 'mysql' ? MYSQL : db === 'postgresql' ? POSTGRESQL : ORACLE;
    set = sets[db] = new Set(src.split(/\s+/).filter(Boolean));
  }
  return set.has(name.toUpperCase());
}
